import {
  emptyFoodGroupServes,
  emptyNutrientVector,
  type Confidence,
  type FoodGroupServes,
  type FoodInput,
  type LogEntryInput,
  type NutrientVector,
} from '@diet-tracker/shared'

/**
 * What Jamie eats: every portion that appears in the demo's food log, with a full nutrient
 * vector for the amount logged (kcal, g, mg, mcg as the nutrient enum says). The figures are
 * ordinary label and food-table values rounded the way the app's own AI estimates round
 * them; they are demo content, not reference data.
 */

interface PortionExtras {
  /** How it got into the log: typed and estimated by AI (the app's main path), or by hand. */
  source?: 'ai' | 'manual'
  confidence?: Confidence
  assumptions?: string[]
}

const portion = (
  name: string,
  quantity: number,
  unit: string,
  grams: number,
  [energy_kcal, protein_g, carbs_g, fat_g]: [number, number, number, number],
  rest: Partial<NutrientVector>,
  foodGroups: Partial<FoodGroupServes>,
  extras: PortionExtras = {},
): LogEntryInput => ({
  name,
  quantity,
  unit,
  grams,
  nutrients: { ...emptyNutrientVector(), energy_kcal, protein_g, carbs_g, fat_g, ...rest },
  foodGroups: { ...emptyFoodGroupServes(), ...foodGroups },
  source: extras.source ?? 'ai',
  foodId: null,
  aiCallId: null,
  assumptions: extras.assumptions ?? [],
  confidence: (extras.source ?? 'ai') === 'ai' ? (extras.confidence ?? 'high') : null,
  brand: null,
  sourceUrl: null,
  saveToLibrary: false,
})

